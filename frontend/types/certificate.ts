export interface CertificateTemplate {
  id: number;
  name: string;
  description?: string;
  templateFile: string;
  thumbnail?: string;
  isDefault: boolean;
  fields?: any;
  status: 'active' | 'inactive';
  createdAt: string;
  updatedAt: string;
}

export interface Certificate {
  id: number;
  userId: number;
  courseId?: number;
  templateId: number;
  certificateNumber: string;
  issueDate: string;
  expiryDate?: string;
  status: 'active' | 'revoked' | 'expired';
  isAutoGenerated: boolean;
  filePath: string;
  metadata?: any;
  createdAt: string;
  updatedAt: string;
  user?: {
    id: number;
    name: string;
    email: string;
  };
  course?: {
    id: number;
    name: string;
    code?: string;
  };
  template?: {
    id: number;
    name: string;
    thumbnail?: string;
  };
}

export interface CertificateFormData {
  userId: number;
  courseId?: number | null;
  templateId: number;
  expiryDate?: string;
  metadata?: any;
}

export interface CertificateTemplateFormData {
  name: string;
  description?: string;
  isDefault?: boolean;
  status?: 'active' | 'inactive';
  fields?: any;
}
